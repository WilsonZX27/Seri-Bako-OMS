import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
import { stageSnapshot, applySnapshotDelta, restoreStagingLedger, checkpointAttachmentRecovery, readLedger, ledgerTables, ledgerFingerprint } from './import-ledger.mjs';
const { PGlite } = await import(pathToFileURL(process.env.PGLITE_MODULE));
const db = new PGlite();
try {
  const fixture = await fs.readFile('scripts/assets/test-asset-db.mjs','utf8');
  await db.exec(fixture.split('await db.exec(`')[1].split('`);')[0]);
  await db.exec(await fs.readFile('supabase/migrations/337_asset_management_foundation.sql','utf8'));
  const id=n=>`00000000-0000-4000-8000-${String(n).padStart(12,'0')}`, company=id(1);
  await db.query('insert into companies values($1),($2)',[company,id(2)]);
  await db.query('insert into branches values($1,$2)',[id(11),company]);
  await db.query("insert into assets(id,company_id,asset_code,item_name) values($1,$2,'FOREIGN','Other company')",[id(200),id(2)]);
  const source = Object.fromEntries(ledgerTables.map(table=>[table,[]]));
  source.asset_import_batches=[{id:id(90),company_id:company,source_sha256:'a'.repeat(64),reconciliation:{rows:1},state:'rehearsal'}];
  source.asset_locations=[{id:id(31),company_id:company,source_name:'Synthetic branch',branch_id:id(11),kind:'branch'}];
  source.assets=[{id:id(40),company_id:company,asset_code:'SB-SYNTHETIC',item_name:'Tray',source_data:{Qty:null,'Original Date':'2026-10-08T09:00:00'},import_batch_id:id(90)}];
  source.asset_attachments=[{id:id(70),company_id:company,asset_id:id(40),source_key:'synthetic-file',source_data:{},url:'https://example.test/file'}];
  source.asset_holdings=[{id:id(60),company_id:company,asset_id:id(40),location_id:id(31),quantity:null,condition:'Good',status:'Active'}];
  await assert.rejects(()=>stageSnapshot(db,source,company,async()=>{throw new Error('Recovery disk unavailable');}),/Recovery disk/);
  assert.equal((await readLedger(db,company)).assets.length,0);
  let initialBackup;
  await stageSnapshot(db,source,company,async value=>{initialBackup=structuredClone(value);});
  assert.equal((await stageSnapshot(db,source,company,async()=>assert.fail('A replay must not replace recovery evidence'))).unchanged,true);
  assert.equal((await db.query("select asset_company_live($1) live",[company])).rows[0].live,false);
  const filePath=`${company}/${id(40)}/legacy-${id(70)}.jpg`;
  await db.query("insert into storage.objects(bucket_id,name) values('asset-documents',$1)",[filePath]);
  await db.query('update asset_attachments set storage_path=$1,content_sha256=$2,verified_at=now() where id=$3',[filePath,'c'.repeat(64),id(70)]);
  await assert.rejects(()=>restoreStagingLedger(db,initialBackup,company),/changed after/);
  await assert.rejects(()=>checkpointAttachmentRecovery(db,initialBackup,company,async()=>{throw new Error('Checkpoint disk unavailable');}),/Checkpoint disk/);
  await db.query("delete from storage.objects where name=$1",[filePath]);
  await assert.rejects(()=>checkpointAttachmentRecovery(db,initialBackup,company,async()=>{}),/object is missing/);
  await db.query("insert into storage.objects(bucket_id,name) values('asset-documents',$1)",[filePath]);
  let copyBackup;
  await checkpointAttachmentRecovery(db,initialBackup,company,async value=>{copyBackup=structuredClone(value);});
  assert.equal(copyBackup.before_fingerprint,initialBackup.before_fingerprint);
  await db.query('update asset_attachments set content_sha256=$1 where id=$2',['d'.repeat(64),id(70)]);
  await assert.rejects(()=>checkpointAttachmentRecovery(db,copyBackup,company,async()=>{}),/replaced attachment/);
  await db.query('update asset_attachments set content_sha256=$1 where id=$2',['c'.repeat(64),id(70)]);

  await db.query("update assets set item_name='Unreviewed' where id=$1",[id(40)]);
  await assert.rejects(()=>checkpointAttachmentRecovery(db,initialBackup,company,async()=>{}),/Unrelated/);
  await db.query("update assets set item_name='Tray' where id=$1",[id(40)]);
  await restoreStagingLedger(db,copyBackup,company);
  await stageSnapshot(db,source,company,async value=>{initialBackup=structuredClone(value);});

  const next=structuredClone(source);
  next.asset_import_batches[0]={...next.asset_import_batches[0],id:id(91),source_sha256:'b'.repeat(64),reconciliation:{rows:2}};
  next.assets[0]={...next.assets[0],item_name:'Corrected tray',import_batch_id:id(91),source_data:{Qty:null,'Original Date':'2026-10-08T09:00:00',Remark:'Source correction'}};
  next.asset_holdings[0].quantity=0;
  next.assets.push({id:id(41),company_id:company,asset_code:'SB-NEW',item_name:'Added tray',source_data:{Qty:3},import_batch_id:id(91)});
  next.asset_holdings.push({id:id(61),company_id:company,asset_id:id(41),location_id:id(31),quantity:3,condition:'Good',status:'Active'});
  const removed=structuredClone(next);removed.assets.shift();
  await assert.rejects(()=>applySnapshotDelta(db,source,removed,company,async()=>{}),/removals/);
  let deltaBackup;
  await applySnapshotDelta(db,source,next,company,async value=>{deltaBackup=structuredClone(value);});
  const imported=await readLedger(db,company);
  assert.equal(imported.asset_holdings.find(row=>row.id===id(60)).quantity,0);
  assert.deepEqual(imported.assets.find(row=>row.id===id(40)).source_data,next.assets[0].source_data);
  assert.equal(imported.asset_import_batches.find(row=>row.id===id(90)).state,'superseded');
  assert.equal((await applySnapshotDelta(db,source,next,company,async()=>assert.fail('No new recovery file for replay'))).unchanged,true);
  await assert.rejects(()=>restoreStagingLedger(db,initialBackup,company),/changed after/);
  const tampered=structuredClone(deltaBackup);tampered.before.assets[0].item_name='Tampered';
  await assert.rejects(()=>restoreStagingLedger(db,tampered,company),/altered recovery/);
  await db.query("update assets set current_details=$1::jsonb where id=$2",[JSON.stringify({Brand:"Native edit"}),id(40)]);
  await assert.rejects(()=>stageSnapshot(db,next,company,async()=>{}),/Native master details/);
  await assert.rejects(()=>restoreStagingLedger(db,deltaBackup,company),/changed after/);
  await db.query("update assets set current_details='{}' where id=$1",[id(40)]);
  assert.equal(ledgerFingerprint(await readLedger(db,company)),deltaBackup.after_fingerprint);
  await db.query("update asset_import_batches set state='live' where id=$1",[id(91)]);
  await assert.rejects(()=>restoreStagingLedger(db,deltaBackup,company),/activated or verified/);
  await db.query("update asset_import_batches set state='rehearsal' where id=$1",[id(91)]);
  await restoreStagingLedger(db,deltaBackup,company);
  assert.equal(ledgerFingerprint(await readLedger(db,company)),deltaBackup.before_fingerprint);
  await restoreStagingLedger(db,initialBackup,company);
  assert.equal((await readLedger(db,company)).assets.length,0);
  assert.equal((await db.query('select count(*)::int n from assets where company_id=$1',[id(2)])).rows[0].n,1);
  console.log('Staging import passed: atomic rollback, exact replay, reviewed final delta, unknown versus zero, durable recovery, stale/tampered/live rejection and company isolation. No activation or production connection.');
} finally { await db.close(); }
