export function formatStatusLabel(status: string | null | undefined) {
  if (!status) return "-";
  const normalized = status.toLowerCase();
  return statusLabels[normalized] ?? normalized.split("_").map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join(" ");
}
